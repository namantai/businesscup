CREATE TABLE compass.user_subscription (
    id uuid PRIMARY KEY,
    owner_id uuid NOT NULL REFERENCES compass.user_account(id) ON DELETE CASCADE,
    name varchar(100) NOT NULL CHECK (length(btrim(name)) > 0),
    catalog_version uuid,
    plan_id text,
    offer_id text,
    currency compass.currency_code NOT NULL,
    amount compass.money_amount,
    price_state text NOT NULL CHECK (price_state IN ('KNOWN','UNKNOWN')),
    price_origin text NOT NULL CHECK (price_origin IN ('USER_REPORTED','CATALOG','UNKNOWN')),
    terms_json jsonb NOT NULL CHECK (jsonb_typeof(terms_json) = 'object'),
    paid_amount compass.money_amount GENERATED ALWAYS AS ((terms_json->>'paidAmount')::numeric) STORED,
    additional_per_period compass.money_amount GENERATED ALWAYS AS ((terms_json->>'additionalPerPeriod')::numeric) STORED,
    transition_cost compass.money_amount GENERATED ALWAYS AS ((terms_json->>'transitionCost')::numeric) STORED,
    billing_zone text GENERATED ALWAYS AS (terms_json->>'billingZone') STORED NOT NULL,
    renewal_anchor date GENERATED ALWAYS AS (make_date(split_part(terms_json->>'renewalAnchor','-',1)::int,split_part(terms_json->>'renewalAnchor','-',2)::int,split_part(terms_json->>'renewalAnchor','-',3)::int)) STORED,
    next_renewal date GENERATED ALWAYS AS (make_date(split_part(terms_json->>'nextRenewal','-',1)::int,split_part(terms_json->>'nextRenewal','-',2)::int,split_part(terms_json->>'nextRenewal','-',3)::int)) STORED,
    paid_from date GENERATED ALWAYS AS (make_date(split_part(terms_json->>'paidFrom','-',1)::int,split_part(terms_json->>'paidFrom','-',2)::int,split_part(terms_json->>'paidFrom','-',3)::int)) STORED,
    paid_until date GENERATED ALWAYS AS (make_date(split_part(terms_json->>'paidUntil','-',1)::int,split_part(terms_json->>'paidUntil','-',2)::int,split_part(terms_json->>'paidUntil','-',3)::int)) STORED,
    trial_until date GENERATED ALWAYS AS (make_date(split_part(terms_json->>'trialUntil','-',1)::int,split_part(terms_json->>'trialUntil','-',2)::int,split_part(terms_json->>'trialUntil','-',3)::int)) STORED,
    commitment_until date GENERATED ALWAYS AS (make_date(split_part(terms_json->>'commitmentUntil','-',1)::int,split_part(terms_json->>'commitmentUntil','-',2)::int,split_part(terms_json->>'commitmentUntil','-',3)::int)) STORED,
    cancellation_available_from date GENERATED ALWAYS AS (make_date(split_part(terms_json->>'cancellationAvailableFrom','-',1)::int,split_part(terms_json->>'cancellationAvailableFrom','-',2)::int,split_part(terms_json->>'cancellationAvailableFrom','-',3)::int)) STORED,
    revision bigint NOT NULL DEFAULT 1 CHECK (revision > 0),
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    UNIQUE(owner_id,name),
    UNIQUE(owner_id,plan_id),
    FOREIGN KEY (catalog_version,plan_id) REFERENCES compass.subscription_plan(version_id,id),
    FOREIGN KEY (catalog_version,offer_id) REFERENCES compass.price_offer(version_id,id),
    CHECK ((catalog_version IS NULL AND plan_id IS NULL AND offer_id IS NULL)
        OR (catalog_version IS NOT NULL AND plan_id IS NOT NULL AND offer_id IS NOT NULL)),
    CHECK ((price_state='UNKNOWN' AND amount IS NULL AND price_origin='UNKNOWN')
        OR (price_state='KNOWN' AND amount IS NOT NULL AND price_origin<>'UNKNOWN')),
    CHECK ((terms_json->>'currency'=currency AND terms_json->>'name'=name
        AND terms_json->>'priceOrigin'=price_origin) IS TRUE),
    CHECK ((terms_json->>'amount')::numeric IS NOT DISTINCT FROM amount),
    CHECK (renewal_anchor <= next_renewal),
    CHECK (paid_from < paid_until),
    CHECK (paid_until <= next_renewal),
    CHECK (trial_until <= next_renewal),
    CHECK ((terms_json->>'status' IN ('ACTIVE','TRIAL','ENDED','UNKNOWN')) IS TRUE),
    CHECK ((terms_json->>'autoRenew' IN ('YES','NO','UNKNOWN')) IS TRUE),
    CHECK ((terms_json->>'obligation' IN ('NONE','UNTIL','UNKNOWN')) IS TRUE),
    CHECK ((terms_json->>'billingPeriod' IN ('MONTH','YEAR')) IS TRUE),
    CHECK ((terms_json->>'mustKeep' IN ('true','false')) IS TRUE),
    CHECK (((terms_json->>'catalogVersion')::uuid IS NOT DISTINCT FROM catalog_version)
        AND (terms_json->>'planId' IS NOT DISTINCT FROM plan_id) AND (terms_json->>'offerId' IS NOT DISTINCT FROM offer_id))
);
CREATE INDEX user_subscription_owner ON compass.user_subscription(owner_id,created_at,id);
